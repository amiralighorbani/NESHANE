def reduce_number(value: int) -> int:
    """کاهش عدد به یک رقم — با نگه‌داشتن اعداد اصلی ۱۱ و ۲۲."""
    while value > 9 and value not in (11, 22):
        value = sum(int(digit) for digit in str(value))
    return value


def life_path(gy: int, gm: int, gd: int) -> int:
    total = sum(int(digit) for digit in f"{gy:04d}{gm:02d}{gd:02d}")
    return reduce_number(total)


def personal_year(gy: int, gm: int, gd: int, year: int) -> int:
    total = sum(int(digit) for digit in f"{gm:02d}{gd:02d}{year:04d}")
    return reduce_number(total)


