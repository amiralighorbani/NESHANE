def polarity_for_year(year: int) -> Dict[str, str]:
    """سال‌های زوج یانگ و سال‌های فرد یین هستند."""
    return POLARITIES[0] if int(year) % 2 == 0 else POLARITIES[1]


def animal_for_year(year: int) -> Dict[str, Any]:
    """موش در ۱۹۰۰ و هر ۱۲ سال یک‌بار تکرار می‌شود؛ قطب سال هم به آن اضافه می‌شود."""
    animal = ANIMALS[(int(year) - 1900) % 12]
    polarity = polarity_for_year(int(year))
    line = POLARITY_LINES.get(str(animal["key"]), {}).get(polarity["key"], "")
    merged: Dict[str, Any] = dict(animal)
    merged["name"] = f"{animal['name']} — {polarity['name']}"
    merged["body"] = f"{animal['body']} {line}".strip()
    merged["gift"] = f"{animal['gift']} • {polarity['gift']}"
    merged["shadow"] = f"{animal['shadow']} • {polarity['shadow']}"
    merged["advice"] = f"{animal['advice']} {polarity['advice']}"
    merged["polarity"] = polarity["name"]
    merged["polarity_note"] = polarity["note"]
    return merged


def animal_entry(animal_key: str, polarity_key: str) -> Dict[str, Any]:
    """یک طالع مشخص از فهرست ۲۴‌تایی (حیوان + قطب)."""
    animal = get_animal(animal_key)
    polarity = POLARITIES[1] if polarity_key == "yin" else POLARITIES[0]
    line = POLARITY_LINES.get(str(animal["key"]), {}).get(polarity["key"], "")
    merged: Dict[str, Any] = dict(animal)
    merged["name"] = f"{animal['name']} — {polarity['name']}"
    merged["body"] = f"{animal['body']} {line}".strip()
    merged["gift"] = f"{animal['gift']} • {polarity['gift']}"
    merged["shadow"] = f"{animal['shadow']} • {polarity['shadow']}"
    merged["advice"] = f"{animal['advice']} {polarity['advice']}"
    merged["polarity"] = polarity["name"]
    return merged


def catalogue() -> List[Dict[str, Any]]:
    """فهرست کامل ۲۴ طالع: هر حیوان در دو قطب."""
    return [animal_entry(str(animal["key"]), polarity["key"]) for animal in ANIMALS for polarity in POLARITIES]


def element_for_year(year: int) -> Dict[str, str]:
    index = ((year - 1900) // 2) % 5
    return ELEMENTS_CYCLE[index]


def get_animal(key: str) -> Dict[str, Any]:
    for animal in ANIMALS:
        if animal["key"] == key:
            return animal
    return ANIMALS[0]


