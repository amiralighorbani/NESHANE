def _shadow_rune(bright: Dict[str, Any]) -> Dict[str, Any]:
    """سنگ سایه را از روی وجه روشن می‌سازد؛ معنا و توصیه کاملاً تازه است."""
    key = str(bright["key"])
    text = SHADOW_TEXT.get(key, {"body": "", "advice": ""})
    return {
        "key": f"shadow-{key}",
        "name": f"{bright['name']} — سایه",
        "glyph": str(bright["glyph"]),
        "keywords": [str(word) for word in bright["keywords"]] + ["سایه", "درس"],
        "upright": text["body"],
        "reversed": f"سایه کنار می‌رود: {bright['upright']}",
        "advice": text["advice"],
        "face": "shadow",
        "shadow_of": key,
    }


