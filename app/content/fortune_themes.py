def _tokens(text: str) -> List[str]:
    return _TOKEN_RE.findall(text)


def _matched_terms(theme: Dict[str, Any], tokens: List[str]) -> int:
    """تعداد واژه‌های متمایز تم که در متن پیدا شده‌اند.

    شمارشِ «واژهٔ متمایز» بهتر از شمارش تکرار است: غزلی که هشت بار «دل» دارد
    هشت برابر عاشقانه‌تر نیست.
    """
    matched = 0
    for term in theme["terms"]:
        if len(term) >= PREFIX_MATCH_MIN:
            found = any(token.startswith(term) for token in tokens)
        else:
            found = term in tokens
        if found:
            matched += 1
    return matched


def score_of(theme: Dict[str, Any], text: str) -> float:
    """امتیاز یک تم در یک متن (همان معیار `detect`، برای مقایسهٔ دو تم)."""
    matched = _matched_terms(theme, _tokens(text))
    return matched / (len(theme["terms"]) ** 0.5)


def detect(text: str) -> List[Dict[str, Any]]:
    """تم‌های غزل را بر اساس واژه‌های شاخص، مرتب‌شده برمی‌گرداند."""
    tokens = _tokens(text)
    scored: List[tuple] = []
    for theme in THEMES:
        matched = _matched_terms(theme, tokens)
        if not matched:
            continue
        # نرمال‌سازی بر اساس گسترهٔ واژه‌ها، تا تم‌های کم‌واژه هم شانس داشته باشند.
        score = matched / (len(theme["terms"]) ** 0.5)
        scored.append((score, matched, theme["key"], theme))
    scored.sort(key=lambda item: (-item[0], -item[1], item[2]))
    return [item[3] for item in scored]


def keywords_for(themes: List[Dict[str, Any]]) -> List[str]:
    """سه برچسب از تم اصلی و تم دوم می‌سازد."""
    if not themes:
        return list(GENERIC_THEME["keywords"])
    picked = list(themes[0]["keywords"][:2])
    if len(themes) > 1:
        for word in themes[1]["keywords"]:
            if word not in picked:
                picked.append(word)
                break
    else:
        picked.append(themes[0]["label"])
    return picked[:3]
