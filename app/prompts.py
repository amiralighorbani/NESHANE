PROMPT_ORDER: List[str] = ["fortune", "test_result", "feedback"]


def get(key: str) -> Dict[str, Any]:
    return PROMPTS.get(key) or PROMPTS["fortune"]


def describe(key: str) -> Dict[str, Any]:
    """تصویرِ قابل‌نمایشِ یک پرامپت برای پنل ادمین (فقط خواندنی)."""
    entry = get(key)
    return {
        "key": key,
        "label": entry["label"],
        "icon": entry["icon"],
        "used_in": entry["used_in"],
        "summary": entry["summary"],
        "system": entry["system"],
        "user_template": entry["user_template"],
        "temperature": entry["temperature"],
        "max_tokens": entry["max_tokens"],
        "output": entry["output"],
        "system_chars": len(entry["system"]),
        "system_lines": len(entry["system"].splitlines()),
    }


def catalogue() -> List[Dict[str, Any]]:
    return [describe(key) for key in PROMPT_ORDER]


def render_user(key: str, **values: Any) -> str:
    """پرامپت کاربر را با مقادیر واقعی پر می‌کند (فقط برای نمایش/ارسال)."""
    template = get(key)["user_template"]
    try:
        return template.format(**values)
    except (KeyError, IndexError, ValueError):
        return template


def json_hint(key: str) -> str:
    return json.dumps({"prompt": key, "output": get(key)["output"]}, ensure_ascii=False)
